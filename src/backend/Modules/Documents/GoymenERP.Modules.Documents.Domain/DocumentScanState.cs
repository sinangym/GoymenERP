namespace GoymenERP.Modules.Documents.Domain;

/// <summary>
/// DEC-DOC-009's malware-scan result of one stored version, kept apart from any business state. A version whose
/// content was not scanned — no scanner is configured, or the scanner could not answer — is stored but is NEVER
/// served (fail-closed); a scanner that finds malware refuses the upload, so an infected version is never stored.
/// A later rescan is not built: when a scanner arrives, a NotScanned version stays not downloadable until a
/// reviewed rescan path records its own result (append-only; the version row never changes).
/// KLN-D60: a PDF the server itself generated (the generated-document port, a template snapshot present) skips the
/// scan and is marked <see cref="SystemGenerated"/>; it keeps its SHA-256 and passes the type/size checks. Only that
/// server-internal producer path may set it: a user upload or a new version is always scanned.
/// </summary>
public enum DocumentScanState
{
    NotScanned = 1,
    Clean = 2,

    /// <summary>KLN-D60: generated by the server, not scanned and served like a clean version; never a user upload.</summary>
    SystemGenerated = 3,
}

/// <summary>Which scan states may be served (signed short access, unchanged).</summary>
public static class DocumentScanStates
{
    /// <summary>A clean scan or a system-generated PDF (KLN-D60); a NotScanned version is never served (DEC-DOC-009).</summary>
    public static bool IsServable(DocumentScanState state) =>
        state is DocumentScanState.Clean or DocumentScanState.SystemGenerated;
}
